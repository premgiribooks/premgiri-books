const { join } = require("node:path");

/**
 * Puppeteer's default cache directory is a per-OS-user global location
 * (e.g. `~/.cache/puppeteer`) — fine for a plain dev/server install, but
 * unusable for electron-builder's `extraResources`, which needs a stable,
 * project-relative path to bundle into the packaged app (78-pdf-generation.md's
 * "known open item"). This config, read automatically by both `pnpm install`'s
 * puppeteer postinstall step and the `puppeteer browsers install` CLI, moves
 * the download to `.cache/puppeteer` inside the project instead — gitignored
 * (it's a large binary, regenerated by `pnpm install` like `.next/`), but a
 * predictable path `package.json`'s `build.extraResources` and
 * `electron/server.ts`'s packaged-mode `PUPPETEER_CACHE_DIR` can both target.
 *
 * @type {import("puppeteer").Configuration}
 */
module.exports = {
  cacheDirectory: join(__dirname, ".cache", "puppeteer"),
};
